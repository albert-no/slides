#!/usr/bin/env python3
"""Emit the inline SVG for lec14 S40 (P4, job 2026-11-22-lec14-finale-refresh).

Source: Greenblatt, Shlegeris, Sachan & Roger, "AI Control: Improving Safety
Despite Intentional Subversion", ICML 2024, arXiv 2312.06942v5, Table 2.
Rows used (unchanged, no transformation other than linear scaling):
  Upfront auditing     usefulness 100%  safety 15%
  Trusted monitoring   usefulness  97%  safety 62%
Safety = probability the protocol never submits backdoored code in a 5,000-problem
run (against the best attack found). Usefulness = correctness rescaled so that
GPT-3.5 = 0% and GPT-4 = 100%. Audit budget 2%. No uncertainty is reported in
Table 2, so none is drawn.

Usage: python3 p4-gen-s40-bars.py > snippet.svg   (paste into the S40 slide)
"""

ROWS = [("Upfront audit", 15, 100), ("Trusted monitoring", 62, 97)]
PANELS = [("Safety", 1, 300, "#003876"), ("Usefulness", 2, 680, "#6b7280")]
SCALE = 2.9          # viewBox units per percentage point: 100% = 290 units
ROW_Y = [62, 142]    # bar tops
BAR_H = 52
FS, FS_SMALL = 24, 20


def main() -> None:
    out = ['<svg class="l14d-svg" viewBox="0 0 1000 250" role="img" '
           'aria-label="Bars from Greenblatt et al. Table 2: safety 15% upfront audit vs 62% '
           'trusted monitoring; usefulness 100% vs 97%">']
    out.append(f'<!-- generated by figs/lec14-finale-refresh/p4-gen-s40-bars.py; '
               f'x = panel_x0 + {SCALE} * percent -->')
    for (label, _s, _u), y in zip(ROWS, ROW_Y):
        out.append(f'<text x="285" y="{y + BAR_H / 2 + 8}" font-size="{FS}" font-weight="700" '
                   f'fill="#1a1a1a" text-anchor="end">{label}</text>')
    for title, idx, x0, color in PANELS:
        out.append(f'<text x="{x0}" y="34" font-size="{FS}" font-weight="700" fill="{color}">{title}</text>')
        out.append(f'<line x1="{x0}" y1="48" x2="{x0}" y2="208" stroke="#6b7280" stroke-width="2"/>')
        for tick in (0, 50, 100):
            tx = x0 + SCALE * tick
            out.append(f'<text x="{tx}" y="236" font-size="{FS_SMALL}" fill="#6b7280" '
                       f'text-anchor="middle">{tick}%</text>')
            if tick:
                out.append(f'<line x1="{tx}" y1="48" x2="{tx}" y2="208" stroke="#d1d5db" '
                           f'stroke-width="1.5" stroke-dasharray="4 4"/>')
        for row, y in zip(ROWS, ROW_Y):
            v = row[idx]
            w = SCALE * v
            out.append(f'<rect x="{x0}" y="{y}" width="{w:.1f}" height="{BAR_H}" fill="{color}"/>')
            if v >= 40:
                out.append(f'<text x="{x0 + w - 10:.1f}" y="{y + BAR_H / 2 + 8}" font-size="{FS}" '
                           f'font-weight="700" fill="#fff" text-anchor="end">{v}%</text>')
            else:
                out.append(f'<text x="{x0 + w + 10:.1f}" y="{y + BAR_H / 2 + 8}" font-size="{FS}" '
                           f'font-weight="700" fill="{color}" text-anchor="start">{v}%</text>')
    out.append('</svg>')
    print("\n".join(out))


if __name__ == "__main__":
    main()
