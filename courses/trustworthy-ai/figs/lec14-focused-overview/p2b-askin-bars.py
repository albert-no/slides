#!/usr/bin/env python3
"""Emit the inline SVG bar charts for lec14 S74a and S74b (P2b, job 2026-11-27-lec14-focused-overview).

Source: Askin, Ustaomeroglu, Nayak, Joshi, Qu & Joe-Wong, "Examining the Impact of
Data and Training Methods on Emergent and Subliminal Misalignment", arXiv 2605.12798v2
(10 Nov 2026, preprint). https://arxiv.org/html/2605.12798v2

Inputs, copied unchanged from the source tables (values are percentages):

S74a  Table 1 (Qwen3-14B, narrow-eval EM rate, aggregated by the teacher's misaligned
      task), column "Avg.":
        SFT  (learner trained on teacher-written answers, judge-filtered)   27.1
        OPD  (teacher scores the learner's own tokens; on-policy distill.)  38.9
      Rows "Teacher" (50.6) and "OPTD" (39.7) are not drawn (see notes / PROVENANCE).

S74b  Table 10 (narrow-eval EM rate after three epochs), column "Llama"
      (Llama-3.1-8B-Instruct):
        OPD (Filtered)    39.6   online Gemini-2.5-Flash filter before each update
        OPD (Unfiltered)  39.3

EM rate = share of responses a Gemini-2.5-Flash judge scores alignment < 30 and
coherence > 50 (0-100 scales), §2. The two charts use different models and tables:
they are drawn as separate SVGs and never combined, averaged or connected.
Transformation: linear scaling only, zero-based 0-100% axis (SCALE viewBox units per
percentage point). The tables report no uncertainty, so none is drawn.

Usage: python3 -I p2b-askin-bars.py s74a   (or s74b) > snippet.svg
"""
import sys

CHARTS = {
    "s74a": {
        "source": "Askin et al. arXiv 2605.12798v2 Table 1, Qwen3-14B, Avg. column",
        "rows": [("Teacher-written answers", "learner copies them (SFT)", 27.1, "#6b7280"),
                 ("Teacher scores learner tokens", "learner writes (OPD)", 38.9, "#003876")],
    },
    "s74b": {
        "source": "Askin et al. arXiv 2605.12798v2 Table 10, Llama column, after three epochs",
        "rows": [("Judge filter on", "learner answers filtered", 39.6, "#003876"),
                 ("No filter", "all learner answers used", 39.3, "#003876")],
    },
}

W, H = 1136, 250
X0 = 450             # bar origin (0%)
SCALE = 6.4          # viewBox units per percentage point: 100% = 640 units
ROW_Y = [28, 128]    # bar tops
BAR_H = 64
FS, FS_SUB, FS_TICK = 28, 24, 24


def svg(key: str) -> str:
    c = CHARTS[key]
    rows = c["rows"]
    aria = "; ".join(f"{a}: {v}%" for a, _b, v, _c in rows)
    out = [f'<svg class="fo2b-bars" viewBox="0 0 {W} {H}" role="img" '
           f'aria-label="Bars from {c["source"]}, judged-misaligned rate: {aria}">',
           f'<!-- generated by figs/lec14-focused-overview/p2b-askin-bars.py {key}; '
           f'x = {X0} + {SCALE} * percent -->']
    base_y = ROW_Y[-1] + BAR_H + 14
    for tick in (0, 25, 50, 75, 100):
        tx = X0 + SCALE * tick
        out.append(f'<text x="{tx:.1f}" y="{base_y + 28}" font-size="{FS_TICK}" fill="#6b7280" '
                   f'text-anchor="middle">{tick}%</text>')
        if tick:
            out.append(f'<line x1="{tx:.1f}" y1="{ROW_Y[0] - 10}" x2="{tx:.1f}" y2="{base_y}" '
                       f'stroke="#d1d5db" stroke-width="1.5" stroke-dasharray="4 4"/>')
    out.append(f'<line x1="{X0}" y1="{ROW_Y[0] - 10}" x2="{X0}" y2="{base_y}" stroke="#6b7280" stroke-width="2"/>')
    for (label, sub, v, color), y in zip(rows, ROW_Y):
        out.append(f'<text x="{X0 - 16}" y="{y + 28}" font-size="{FS}" font-weight="700" '
                   f'fill="#1a1a1a" text-anchor="end">{label}</text>')
        out.append(f'<text x="{X0 - 16}" y="{y + 58}" font-size="{FS_SUB}" fill="#6b7280" '
                   f'text-anchor="end">{sub}</text>')
        w = SCALE * v
        out.append(f'<rect x="{X0}" y="{y}" width="{w:.1f}" height="{BAR_H}" fill="{color}"/>')
        out.append(f'<text x="{X0 + w + 12:.1f}" y="{y + BAR_H / 2 + 10}" font-size="{FS}" '
                   f'font-weight="700" fill="{color}" text-anchor="start">{v}%</text>')
    out.append('</svg>')
    return "\n".join(out)


if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1] not in CHARTS:
        sys.exit(__doc__)
    print(svg(sys.argv[1]))
