#!/usr/bin/env python3
"""Emit the inline SVG for lec14 main S40 (P3, job 2026-11-27-lec14-focused-overview).

Safety-only chart. The two-metric chart (safety + usefulness) is a separate,
unchanged asset: figs/lec14-finale-refresh/p4-gen-s40-bars.py (backup S89).

Source: Greenblatt, Shlegeris, Sachan & Roger, "AI Control: Improving Safety
Despite Intentional Subversion", ICML 2024, arXiv 2312.06942v5 (23 Jul 2024),
https://arxiv.org/html/2312.06942v5 , Table 2 ("Best red-team attack policy" /
"Safety" column); same values restated in §3.1.2 ("At 2% budget, the blue team
win probability is 15%") and §3.2 ("The blue team win probability is 62%").
Rows used, values unchanged:
  Upfront auditing (audit the first 2% of problems)      safety 15%
  Trusted monitoring (audit the top 2% most suspicious)  safety 62%
Safety = probability that no backdoored solution is submitted in a whole
simulated 5,000-problem run, against the best attack the red team found.
Audit budget 2%. Table 2 reports no uncertainty, so none is drawn.
Transformation: linear only, x = X0 + SCALE * percent, zero-based 0-100% axis.

Usage: python3 -I p3-control-bars.py > snippet.svg   (paste into the S40 slide)
"""

ROWS = [("Upfront: first 2%", 15), ("Monitoring: top-2% suspicious", 62)]
X0 = 440             # axis origin (viewBox units)
SCALE = 5.3          # viewBox units per percentage point: 100% = 530 units
ROW_Y = [40, 130]    # bar tops
BAR_H = 60
FS, FS_TICK = 26, 22
COLOR = "#003876"


def main() -> None:
    out = ['<svg class="fo3-svg" viewBox="0 0 1000 250" role="img" '
           'aria-label="Bars from Greenblatt et al. Table 2: whole-run safety 15% for upfront '
           'auditing of the first 2% of problems versus 62% for trusted monitoring that audits '
           'the top 2% most suspicious solutions">']
    out.append('<!-- generated by figs/lec14-focused-overview/p3-control-bars.py; '
               f'x = {X0} + {SCALE} * percent -->')
    axis_bottom = ROW_Y[-1] + BAR_H + 16
    out.append(f'<line x1="{X0}" y1="{ROW_Y[0] - 16}" x2="{X0}" y2="{axis_bottom}" '
               'stroke="#6b7280" stroke-width="2"/>')
    for tick in (0, 50, 100):
        tx = X0 + SCALE * tick
        out.append(f'<text x="{tx:.0f}" y="{axis_bottom + 30}" font-size="{FS_TICK}" '
                   f'fill="#4b5563" text-anchor="middle">{tick}%</text>')
        if tick:
            out.append(f'<line x1="{tx:.0f}" y1="{ROW_Y[0] - 16}" x2="{tx:.0f}" y2="{axis_bottom}" '
                       'stroke="#d1d5db" stroke-width="1.5" stroke-dasharray="4 4"/>')
    for (label, v), y in zip(ROWS, ROW_Y):
        ty = y + BAR_H / 2 + 9
        out.append(f'<text x="{X0 - 14}" y="{ty:.0f}" font-size="{FS}" font-weight="700" '
                   f'fill="#1a1a1a" text-anchor="end">{label}</text>')
        w = SCALE * v
        out.append(f'<rect x="{X0}" y="{y}" width="{w:.1f}" height="{BAR_H}" fill="{COLOR}"/>')
        if v >= 40:
            out.append(f'<text x="{X0 + w - 12:.1f}" y="{ty:.0f}" font-size="{FS}" font-weight="700" '
                       f'fill="#fff" text-anchor="end">{v}%</text>')
        else:
            out.append(f'<text x="{X0 + w + 12:.1f}" y="{ty:.0f}" font-size="{FS}" font-weight="700" '
                       f'fill="{COLOR}" text-anchor="start">{v}%</text>')
    out.append('</svg>')
    print("\n".join(out))


if __name__ == "__main__":
    main()
