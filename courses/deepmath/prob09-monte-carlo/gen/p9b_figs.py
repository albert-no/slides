#!/usr/bin/env python3
"""prob09 Parts 02-03 (P2): shape-only SVG figures fig/p9b-*.svg.

Every curve is the exact closed-form density/contribution sampled on a fine grid and
mapped by one linear (or log10) transform per axis; the transform is written into each
SVG as a comment. Math labels are HTML overlay spans in the deck; the positions the
deck uses are printed below as (left%, top%) of the viewBox.
Schematic dot positions (S45) and the S63a locations are hand-placed and labelled as schematic on the slide.
No random numbers are drawn anywhere.  Run:  python3 gen/p9b_figs.py
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'fig')
BLUE, GREEN, RED, GREY, LGREY, BAND = '#003876', '#1a7a3d', '#c0392b', '#666666', '#9aa4af', '#e3eaf3'
FONT = "font-family=\"Noto Sans, Arial, sans-serif\""


class Plot:
    def __init__(self, W, H, box, xr, yr, ylog=False):
        self.W, self.H = W, H
        self.x0, self.y0, self.x1, self.y1 = box          # plot box in px (left, top, right, bottom)
        self.xr, self.yr, self.ylog = xr, yr, ylog
        self.parts = []

    def X(self, x):
        return self.x0 + (x - self.xr[0]) / (self.xr[1] - self.xr[0]) * (self.x1 - self.x0)

    def Y(self, y):
        if self.ylog:
            y = math.log10(y)
        return self.y1 - (y - self.yr[0]) / (self.yr[1] - self.yr[0]) * (self.y1 - self.y0)

    def pct(self, px, py):
        return f"left:{100*px/self.W:.1f}%; top:{100*py/self.H:.1f}%"

    def add(self, s):
        self.parts.append(s)

    def curve(self, fn, a, b, color, width=4, dash=None, n=400, fill_to=None, fill=None):
        pts = [(self.X(a + (b - a) * i / n), self.Y(fn(a + (b - a) * i / n))) for i in range(n + 1)]
        d = ' '.join(f"{x:.1f},{y:.1f}" for x, y in pts)
        if fill:
            base = self.Y(fill_to) if fill_to is not None else self.y1
            self.add(f'<polygon points="{pts[0][0]:.1f},{base:.1f} {d} {pts[-1][0]:.1f},{base:.1f}" fill="{fill}" stroke="none"/>')
        da = f' stroke-dasharray="{dash}"' if dash else ''
        self.add(f'<polyline points="{d}" fill="none" stroke="{color}" stroke-width="{width}"{da} stroke-linejoin="round"/>')

    def axes(self, xticks, yticks, xfmt=str, yfmt=str, fs=24):
        self.add(f'<line x1="{self.x0}" y1="{self.y1}" x2="{self.x1}" y2="{self.y1}" stroke="#333" stroke-width="2"/>')
        self.add(f'<line x1="{self.x0}" y1="{self.y0}" x2="{self.x0}" y2="{self.y1}" stroke="#333" stroke-width="2"/>')
        for t in xticks:
            x = self.X(t)
            self.add(f'<line x1="{x:.1f}" y1="{self.y1}" x2="{x:.1f}" y2="{self.y1+8}" stroke="#333" stroke-width="2"/>')
            if xfmt(t):
                self.add(f'<text x="{x:.1f}" y="{self.y1+32}" font-size="{fs}" text-anchor="middle" fill="#333" {FONT}>{xfmt(t)}</text>')
        for t in yticks:
            y = self.Y(10**t if self.ylog else t)
            self.add(f'<line x1="{self.x0-8}" y1="{y:.1f}" x2="{self.x0}" y2="{y:.1f}" stroke="#333" stroke-width="2"/>')

    def vline(self, x, color=GREY, dash='8 6', width=2.5, top=None):
        X = self.X(x)
        self.add(f'<line x1="{X:.1f}" y1="{self.y0 if top is None else top}" x2="{X:.1f}" y2="{self.y1}" stroke="{color}" stroke-width="{width}" stroke-dasharray="{dash}"/>')

    def band(self, a, b, fill=BAND):
        self.add(f'<rect x="{self.X(a):.1f}" y="{self.y0}" width="{self.X(b)-self.X(a):.1f}" height="{self.y1-self.y0}" fill="{fill}"/>')

    def text(self, x, y, s, fs=24, color='#333', anchor='middle', weight=500):
        self.add(f'<text x="{x:.1f}" y="{y:.1f}" font-size="{fs}" text-anchor="{anchor}" fill="{color}" font-weight="{weight}" {FONT}>{s}</text>')

    def save(self, name, comment):
        body = '\n'.join(self.parts)
        svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {self.W} {self.H}" width="{self.W}" height="{self.H}">\n'
               f'<!-- generated by gen/p9b_figs.py. {comment} -->\n{body}\n</svg>\n')
        with open(os.path.join(OUT, name), 'w') as fh:
            fh.write(svg)
        print(f"wrote fig/{name}")


def report(P, label, px, py):
    print(f"   {label:<34s} {P.pct(px, py)}")


