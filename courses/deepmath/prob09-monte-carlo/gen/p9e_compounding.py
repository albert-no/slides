#!/usr/bin/env python3
"""Exact independent-token compounding toy (evidence E20) for prob09 slide S103.

Deterministic: closed-form values only, no random numbers (no seed needed).

Toy: behavior tokens are independent binary draws with pi_b = (1/2, 1/2);
target tokens are independent with pi_theta = ((1+s)/2, (1-s)/2), s = sqrt(0.1).
Per-token weight w_t = pi_theta/pi_b takes values 1+s and 1-s with probability 1/2 each
under pi_b, so E[w_t] = 1 and E[w_t^2] = 1 + s^2 = 1.1.  Independence under pi_b gives
E[(prod_t w_t)^2] = 1.1^T.  The population proxy n / E[w^2] is NOT an observed ESS.

Writes fig/p9e-compounding.svg (shapes only; math labels are HTML overlays in the deck)
and prints every number the slide and notes use, plus the overlay positions.
Run from anywhere:  python3 gen/p9e_compounding.py
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "fig", "p9e-compounding.svg")

s = math.sqrt(0.1)
p = ((1 + s) / 2, (1 - s) / 2)   # target pi_theta per token
q = (0.5, 0.5)                    # behavior pi_b per token
w = (p[0] / q[0], p[1] / q[1])
Ew = sum(qi * wi for qi, wi in zip(q, w))
Ew2 = sum(qi * wi * wi for qi, wi in zip(q, w))

print("per-token target p =", p)
print("per-token weights   =", w)
print("E_q[w_t]   = %.12f" % Ew)
print("E_q[w_t^2] = %.12f" % Ew2)
for T in (1, 10, 25, 50, 75, 100):
    print("T=%3d  E_q[w^2] = 1.1^T = %.5f   log10 = %.4f" % (T, Ew2 ** T, T * math.log10(Ew2)))
m100 = Ew2 ** 100
print("ln(1.1^100) = 100 ln 1.1 = %.4f" % (100 * math.log(1.1)))
n = 10 ** 6
print("population proxy n/E[w^2] at n=1e6, T=100: %.4f" % (n / m100))

# ---- plot geometry: X = 110 + 5.8 T ; Y = 380 - (320/4.5) log10(value) ----
W, H = 720, 460
def X(T): return 110 + 5.8 * T
def Y(L): return 380 - (320 / 4.5) * L

pts = " ".join("%.1f,%.1f" % (X(T), Y(T * math.log10(Ew2))) for T in range(0, 101))
grid = "\n".join(
    '  <line x1="110" y1="%.1f" x2="690" y2="%.1f" stroke="#d5dbe2" stroke-width="1.5"/>' % (Y(L), Y(L))
    for L in (1, 2, 3, 4))
xt = "\n".join(
    '  <line x1="%.1f" y1="380" x2="%.1f" y2="388" stroke="#222" stroke-width="2"/>' % (X(T), X(T))
    for T in (0, 25, 50, 75, 100))
yt = "\n".join(
    '  <line x1="102" y1="%.1f" x2="110" y2="%.1f" stroke="#222" stroke-width="2"/>' % (Y(L), Y(L))
    for L in (0, 1, 2, 3, 4))
marks = "\n".join(
    '  <circle cx="%.1f" cy="%.1f" r="7" fill="#c0392b"/>' % (X(T), Y(T * math.log10(Ew2)))
    for T in (50, 100))
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}">
  <!-- generated by gen/p9e_compounding.py: exact E[w^2] = 1.1^T, log10 vertical axis.
       X = 110 + 5.8 T ; Y = 380 - (320/4.5) log10(value) -->
{grid}
  <line x1="110" y1="380" x2="690" y2="380" stroke="#222" stroke-width="2.5"/>
  <line x1="110" y1="380" x2="110" y2="50" stroke="#222" stroke-width="2.5"/>
{xt}
{yt}
  <polyline points="{pts}" fill="none" stroke="#003876" stroke-width="5"/>
{marks}
</svg>
'''
with open(OUT, "w") as f:
    f.write(svg)
print("wrote", os.path.normpath(OUT))

def pct(x, y):
    return "left:%.2f%%;top:%.2f%%" % (100 * x / W, 100 * y / H)
print("overlay positions (viewBox %dx%d):" % (W, H))
for T in (0, 25, 50, 75, 100):
    print("  x tick T=%d  -> %s" % (T, pct(X(T), 405)))
for L in (0, 1, 2, 3, 4):
    print("  y tick 10^%d -> right edge %s" % (L, pct(96, Y(L))))
for T in (50, 100):
    L = T * math.log10(Ew2)
    print("  point T=%d -> %s" % (T, pct(X(T), Y(L))))
